function downloadReport() {
  const content = `FEDLUNG AI — DIAGNOSIS REPORT
============================================
Patient ID: LC-2026-001
Date: ${new Date().toLocaleString()}
Hospital: Hospital A (CT Imaging Center)
Image Type: CT Scan

DIAGNOSIS: Malignant Lung Cancer
Confidence: 94%
Severity: High Risk
Federated Learning Status: Completed (v2.5)
Explainable AI Status: Generated (Grad-CAM + SHAP)

RECOMMENDATION:
Immediate clinical evaluation and oncology consultation advised.

Generated by FedLung AI — Federated Explainable Multi-Modal Deep Learning Framework.
`;
  const blob = new Blob([content], { type: "text/plain" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "FedLung_Report_LC-2026-001.txt";
  a.click();
  URL.revokeObjectURL(url);
}

